import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "web", "lib", "database.generated.types.ts");
const projectRefPath = path.join(root, "supabase", ".temp", "project-ref");
const schemas = (process.env.SUPABASE_SCHEMAS ?? "public")
  .split(",")
  .map((schema) => schema.trim())
  .filter(Boolean);

function linkedProjectRef() {
  if (!existsSync(projectRefPath)) return null;
  const ref = readFileSync(projectRefPath, "utf8").trim();
  return ref || null;
}

const projectRef = process.env.SUPABASE_PROJECT_ID ?? linkedProjectRef();
const args = ["gen", "types", "typescript"];

for (const schema of schemas) {
  args.push("--schema", schema);
}

if (projectRef) {
  args.push("--project-id", projectRef);
} else {
  args.push("--local");
}

function findWindowsCommand() {
  const pathDirs = (process.env.PATH ?? "").split(path.delimiter);
  for (const dir of pathDirs) {
    for (const candidate of ["supabase.exe", "supabase.cmd", "supabase.bat"]) {
      const fullPath = path.join(dir, candidate);
      if (existsSync(fullPath)) return fullPath;
    }
  }
  return null;
}

let command = "supabase";
let commandArgs = args;

if (process.platform === "win32") {
  const windowsCommand = findWindowsCommand();
  if (windowsCommand?.endsWith(".cmd") || windowsCommand?.endsWith(".bat")) {
    command = process.env.ComSpec ?? "cmd.exe";
    commandArgs = ["/d", "/c", windowsCommand, ...args];
  } else if (windowsCommand) {
    command = windowsCommand;
  }
}

const result = spawnSync(command, commandArgs, {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "pipe"],
});

if (result.error?.code === "ENOENT") {
  console.error("Supabase CLI was not found. Install it, then rerun `npm run generate:supabase-types`.");
  process.exit(1);
}

if (result.error) {
  console.error(result.error.message);
  process.exit(1);
}

if (result.status !== 0) {
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  process.exit(result.status ?? 1);
}

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// This file is generated by scripts/generate-supabase-types.mjs. Do not edit.\n\n${result.stdout}`,
);
